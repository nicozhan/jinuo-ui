#!/usr/bin/env python3
"""Sync the web prototype's artwork, typefaces and catalogue into this Android project.

    python3 tools/sync_from_web.py

Source of truth: ../../kiosk.js (CATALOG), ../../assets/**.
The HTML prototype is only READ here; this script never writes into it.

Outputs:
  app/src/main/res/drawable-nodpi/*.png|jpg   logo, banner, 22 card + 22 hero images
  app/src/main/res/font/*.ttf                 Fraunces + Instrument Sans (woff2 -> ttf)
  app/src/main/java/com/jinuo/kiosk/data/Catalog.kt
"""
from __future__ import annotations

import json
import re
import shutil
import sys
from pathlib import Path

COMPOSE = Path(__file__).resolve().parents[1]
WEB = COMPOSE.parent
APP = COMPOSE / "app" / "src" / "main"
DRAWABLE = APP / "res" / "drawable-nodpi"
FONT = APP / "res" / "font"
DATA = APP / "java" / "com" / "jinuo" / "kiosk" / "data"

for d in (DRAWABLE, FONT, DATA):
    d.mkdir(parents=True, exist_ok=True)


def kstr(value: str) -> str:
    """Kotlin string literal."""
    return json.dumps(value, ensure_ascii=False)


def res_name(prefix: str, product_id: str) -> str:
    return prefix + "_" + re.sub(r"[^a-z0-9_]", "_", product_id.lower())


# ---- 1. read the runtime catalogue -------------------------------------------------
js = (WEB / "kiosk.js").read_text(encoding="utf-8")
block = re.search(r"/\* CATALOG_START \*/(.*?)/\* CATALOG_END \*/", js, re.S).group(1)
catalog = json.loads(re.search(r"var CATALOG = (\[.*?\]);", block, re.S).group(1))
assert len(catalog) == 22, "expected 22 products"

# ---- 2. copy artwork ----------------------------------------------------------------
copied = []
for src, name in [
    (WEB / "assets/logo.png", "kiosk_logo.png"),
    (WEB / "assets/img/7b963e7086e19ff8.jpg", "kiosk_banner.jpg"),
]:
    shutil.copyfile(src, DRAWABLE / name)
    copied.append(name)

for p in catalog:
    for key, prefix in (("card", "card"), ("hero", "hero")):
        src = WEB / p[key]
        if not src.exists():
            raise FileNotFoundError(src)
        name = res_name(prefix, p["id"]) + ".png"
        shutil.copyfile(src, DRAWABLE / name)
        copied.append(name)

# ---- 3. convert woff2 -> static ttf (Android cannot load woff2) ------------------
# The web fonts are variable and Fraunces defaults to wght=900 / opsz=9.
# Instance them at the weights the Compose design actually uses, otherwise a
# plain conversion renders every headline bold at the wrong optical size.
try:
    from fontTools.ttLib import TTFont
    from fontTools.varLib.instancer import instantiateVariableFont
except ImportError:
    print("fontTools missing: pip install fonttools brotli", file=sys.stderr)
    raise

for old in FONT.glob("*.ttf"):
    old.unlink()

instances = [
    ("fraunces.woff2", "fraunces_400.ttf", {"wght": 400, "opsz": 48}),
    ("fraunces.woff2", "fraunces_500.ttf", {"wght": 500, "opsz": 48}),
    ("fraunces.woff2", "fraunces_600.ttf", {"wght": 600, "opsz": 48}),
    ("instrument-sans.woff2", "instrument_sans_400.ttf", {"wght": 400}),
    ("instrument-sans.woff2", "instrument_sans_600.ttf", {"wght": 600}),
]
for src_name, out_name, axes in instances:
    f = instantiateVariableFont(
        TTFont(WEB / "assets" / "fonts" / src_name), axes, inplace=False, optimize=True
    )
    f.flavor = None
    f.save(FONT / out_name)
    copied.append(out_name)

# ---- 4. emit compile-time-safe Kotlin catalogue -----------------------------------
lines = [
    "// GENERATED by tools/sync_from_web.py — do not edit by hand.",
    "// Source: ../../kiosk.js CATALOG (22 drinks, 5 categories, CHF 3.50).",
    "package com.jinuo.kiosk.data",
    "",
    "import androidx.annotation.DrawableRes",
    "import com.jinuo.kiosk.R",
    "",
    "data class Product(",
    "    val id: String,",
    "    val name: String,",
    "    val category: String,",
    "    val kind: String,",
    "    val price: Double,",
    "    @DrawableRes val card: Int,",
    "    @DrawableRes val hero: Int,",
    ")",
    "",
    "const val CURRENCY = \"CHF\"",
    "const val DEFAULT_PRICE = 3.5",
    "",
    "val CATS = listOf(\"CLASSICS\", \"ESPRESSO\", \"MILK\", \"TEA\", \"FRAPPE\")",
    "",
    "val CATALOG: List<Product> = listOf(",
]
for p in catalog:
    lines.append(
        "    Product(%s, %s, %s, %s, %.2f, R.drawable.%s, R.drawable.%s),"
        % (
            kstr(p["id"]),
            kstr(p["name"]),
            kstr(p["cat"]),
            kstr(p["kind"]),
            float(p["price"]),
            res_name("card", p["id"]),
            res_name("hero", p["id"]),
        )
    )
lines += [")", ""]
(DATA / "Catalog.kt").write_text("\n".join(lines), encoding="utf-8")

print("synced %d resources from %s" % (len(copied), WEB))
print("wrote %s" % (DATA / "Catalog.kt"))
