# ---------------------------------------------------------------------------
# v8 · same-function button contract
# ---------------------------------------------------------------------------
# Only buttons that share BOTH function and visual language are grouped.
# Six families, each with ONE height, ONE corner radius, ONE label type.
# Width is deliberately NOT unified: a full-width page CTA and two side-by-
# side modal CTAs must keep their layout widths. Colour is NOT unified either:
# brand/accent fills stay as designed, only the label ink is pinned.
#
# Deliberately excluded (different function or different design):
#   * "Return to Menu"       - plain text link, not a filled button
#   * carousel dots / arrows - navigation affordances, not buttons
#   * product / sold-out cards, category tabs, qty +/- steppers, close glyphs
#   * v7 overlay dialogs (k-limit-ok, k-empty-cta) - separate overlay scale
def btn_family_css(group, h, r, fs, kc, fw, color=None):
    """Shape rule targets the wrapper AND its empty Figma paint layer."""
    shape = (
        'body[data-refine] [data-btn-group="%s"],\n'
        'body[data-refine] [data-btn-group="%s"] > div:empty:first-child{\n'
        '  height:var(%s)!important;min-height:0!important;\n'
        '  border-radius:var(%s)!important;border:0!important;\n'
        '  box-sizing:border-box!important;\n'
        '}\n' % (group, group, h, r))
    sels = ['body[data-refine] [data-btn-group="%s"] [data-kc="%s"]'
            % (group, kc)]
    if group in ('primary', 'modal-cta', 'bottom-action'):
        sels.append('body[data-refine] [data-btn-group="%s"] .cta-label' % group)
    decl = ('  font-family:var(--k-font-display)!important;\n'
            '  font-size:var(%s)!important;\n'
            '  font-weight:var(%s)!important;\n'
            '  letter-spacing:var(--k-ls-none)!important;\n'
            '  white-space:nowrap!important;\n'
            '  text-align:center!important;\n' % (fs, fw))
    if color:
        decl += '  color:var(%s)!important;\n' % color
    return shape + ',\n'.join(sels) + '{\n' + decl + '}\n'


