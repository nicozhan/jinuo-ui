def patch_docs(s):
    s = re.sub(r'\s*<!-- VERSION_NOTE_START -->.*?<!-- VERSION_NOTE_END -->',
               '', s, flags=re.S)
    i = s.find('<p class="lead">')
    if i < 0:
        return s
    j = s.find('</p>', i)
    return s[:j + 4] + VERSION_NOTE + s[j + 4:]


