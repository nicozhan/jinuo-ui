def add_links(s):
    s = re.sub(r'\s*<link rel="stylesheet" href="\.\./tokens\.css">', '', s)
    s = re.sub(r'\s*<link rel="stylesheet" href="\.\./refine\.css">', '', s)
    return s.replace('</head>', LINKS + '</head>', 1)


def add_body(s, slug):
    s, n = re.subn(r'<body[^>]*>',
                   '<body data-refine="1" data-page="%s">' % slug, s, count=1)
    if n != 1:
        raise SystemExit('body tag not found in %s' % slug)
    return s


def mark(s, needle, attrs, count=0):
    """Add attributes to every tag containing `needle` (before its closing >)."""
    out, n = [], 0
    pos = 0
    for m in re.finditer(r'<[^>]*>', s):
        tag = m.group(0)
        if needle in tag and attrs not in tag and not tag.startswith('</'):
            new = tag[:-1].rstrip() + ' ' + attrs + '>'
            out.append(s[pos:m.start()]); out.append(new)
            pos = m.end(); n += 1
            if count and n >= count:
                break
    out.append(s[pos:])
    return ''.join(out), n


def tag_attr(s, pattern, attr):
    """Add `attr` to every tag matching regex `pattern` that lacks data-kc."""
    def repl(m):
        tag = m.group(0)
        if 'data-kc=' in tag:
            return tag
        return tag[:-1].rstrip() + ' ' + attr + '>'
    return re.sub(pattern, repl, s)


def tag_by_key(s, key, kc):
    pat = r'<span[^>]*data-i18n="' + re.escape(key) + r'"[^>]*>'
    return tag_attr(s, pat, 'data-kc="%s"' % kc)


def parent_class_font(s, cls):
    m = re.search(r'\.' + re.escape(cls) + r'\{([^}]*)\}', s)
    if not m:
        return ''
    f = re.search(r'font-family:([^;]+);', m.group(1))
    return f.group(1) if f else ''


