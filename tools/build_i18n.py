#!/usr/bin/env python3
"""Build the single-language runtime from i18n.json.

  python3 tools/build_i18n.py

* Regenerates i18n.js (a plain global, so it also works over file://).
* Tags every visible leaf-text element in pages/*.html with data-i18n.
* Marks code-like strings with data-nolang so the purity audit can skip them.
* Tags the three order-option lines with data-order-opts.
* Injects <script src="../i18n.js"> before kiosk.js.
* Writes partials/i18n-coverage.json.

Idempotent: run it again after build_cart_drawer.py / apply_products.py.
"""
import html
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'i18n.json'
PRODUCTS = ROOT / 'products.json'
OUT = ROOT / 'i18n.js'
COVERAGE = ROOT / 'partials' / 'i18n-coverage.json'
PAGES = sorted((ROOT / 'pages').glob('*.html'))

LINK = '<script src="../i18n.js"></script>'
DYNAMIC_ATTRS = ('data-slot-name', 'data-slot-cn', 'data-cart-name',
                 'data-order-name', 'data-modal-name', 'data-cart-qty',
                 'data-cart-subtotal', 'data-cart-total')
OPTS_TEXTS = ['少糖 · 热饮', '多冰 · 少糖', '少冰 · 正常糖']
COUNT_TEXT = '3 items'
LANG_LABELS = {'Français', 'English'}
LEAF = re.compile(r'<(?P<tag>span|div|title|p|h3|button|label|b|strong)\b(?P<attrs>[^>]*)>(?P<text>[^<]*)</(?P=tag)>', re.I)
INJECTED_ATTR = re.compile(r'\s+data-(?:i18n|nolang|order-opts|order-count|lang-toggle)(?:="[^"]*")?')


def norm(s):
    return re.sub(r'\s+', ' ', html.unescape(s)).strip()


def main():
    data = json.loads(SRC.read_text())
    prods = json.loads(PRODUCTS.read_text())['products']
    langs = data['langs']

    # Expand the compact [en, fr, zh] tuples into three flat dictionaries,
    # and add product names (full, short and Chinese) as static-safe keys.
    data['t']['@langLabel'] = ['English', 'Français', '中文']
    dicts = {l: {} for l in langs}
    for key, vals in data['t'].items():
        for l, v in zip(langs, vals):
            dicts[l][key] = v
    for p in prods:
        info = data['products'][p['id']]
        triple = [info['en'], info['fr'], info['zh']]
        for l, v in zip(langs, triple):
            dicts[l]['p.' + p['id']] = v
        for l, v in zip(langs, info['tag']):
            dicts[l]['p.' + p['id'] + '.tag'] = v
        for alias in {p['name'], p['short'], p['cn']}:
            for l, v in zip(langs, triple):
                dicts[l].setdefault(alias, v)

    nolang = set(data['nolang'])
    coverage = {'pages': {}, 'missing': [], 'counts': {}}
    for page in PAGES:
        s = page.read_text()
        # remove artefacts from a previous run
        s = s.replace(LINK + '\n', '').replace(LINK, '')
        s = INJECTED_ATTR.sub('', s)
        stats = {'translated': 0, 'nolang': 0, 'dynamic': 0, 'labels': 0, 'opts': 0}
        opt_i = [0]

        def repl(m):
            tag, attrs, raw = m.group('tag'), m.group('attrs'), m.group('text')
            txt = norm(raw)
            if not txt:
                return m.group(0)
            if any(re.search(r'\b' + re.escape(a) + r'\b', attrs) for a in DYNAMIC_ATTRS):
                stats['dynamic'] += 1
                return m.group(0)
            extra = ''
            if txt in LANG_LABELS:
                key = '@langLabel'
                extra = ' data-lang-toggle="1"'
                stats['labels'] += 1
            elif txt in nolang or not re.search(r'[A-Za-z\u4e00-\u9fff]', txt):
                stats['nolang'] += 1
                return '<%s%s data-nolang="1">%s</%s>' % (tag, attrs, raw, tag)
            else:
                key = txt
                if key not in data['t']:
                    coverage['missing'].append({'page': page.name, 'text': key})
            if txt in OPTS_TEXTS:
                extra += ' data-order-opts="%d"' % opt_i[0]
                opt_i[0] += 1
                stats['opts'] += 1
            if txt == COUNT_TEXT:
                extra += ' data-order-count="1"'
            stats['translated'] += 1
            return '<%s%s data-i18n="%s"%s>%s</%s>' % (
                tag, attrs, html.escape(key, quote=True), extra, raw, tag)

        s = LEAF.sub(repl, s)
        if '<script src="../kiosk.js"' not in s:
            raise RuntimeError('kiosk.js script tag missing in ' + page.name)
        s = s.replace('<script src="../kiosk.js"', LINK + '\n<script src="../kiosk.js"', 1)
        page.write_text(s)
        coverage['pages'][page.name] = stats

    bundle = {
        'langs': langs,
        'white': data['white'],
        'en': dicts['en'], 'fr': dicts['fr'], 'zh': dicts['zh'],
        'products': data['products'],
    }
    js = '/* Generated by tools/build_i18n.py — single-language runtime. Do not edit by hand. */\n'
    js += 'window.KIOSK_I18N = ' + json.dumps(bundle, ensure_ascii=False, separators=(',', ':')) + ';\n'
    js += r'''
/* Purity audit: returns every visible text that still contains a foreign word.
   A "foreign word" is any word used by another language's dictionary but not by
   the current one; brand names / currency codes are whitelisted. */
window.KIOSK_I18N.audit = function (lang, doc) {
  doc = doc || document;
  var self = this, D = { en: self.en, fr: self.fr, zh: self.zh };
  var cur = D[lang] || D.en, white = self.white, foreign = {};
  function words(v) {
    return String(v).toLowerCase().replace(/[^a-zà-ÿ\u4e00-\u9fff']+/g, ' ')
      .split(/\s+/).filter(function (w) { return w.length >= 2; });
  }
  ['en', 'fr', 'zh'].forEach(function (l) {
    if (l === lang) return;
    Object.keys(D[l]).forEach(function (k) {
      words(D[l][k]).forEach(function (w) { if (white.indexOf(w) < 0) foreign[w] = 1; });
    });
  });
  Object.keys(cur).forEach(function (k) {
    words(cur[k]).forEach(function (w) { delete foreign[w]; });
  });
  var bad = [], nodes = doc.querySelectorAll('#stage *, #k-layer *, #k-console *');
  function flag(t, why) { if (bad.length < 40) bad.push({ text: t.slice(0, 90), why: why }); }
  for (var i = 0; i < nodes.length; i++) {
    var e = nodes[i];
    if (e.tagName === 'SCRIPT' || e.tagName === 'STYLE') continue;
    if (e.closest && e.closest('[data-nolang]')) continue;
    var t = '';
    for (var j = 0; j < e.childNodes.length; j++) {
      if (e.childNodes[j].nodeType === 3) t += e.childNodes[j].nodeValue;
    }
    t = t.replace(/\s+/g, ' ').trim();
    if (!t) continue;
    if (lang !== 'zh' && /[\u4e00-\u9fff]/.test(t)) { flag(t, 'CJK in ' + lang); continue; }
    if (lang !== 'fr' && /[àâçéèêëîïôùûüœÀÂÇÉÈÊËÎÏÔÙÛÜŒ]/.test(t)) {
      flag(t, 'French accents in ' + lang); continue;
    }
    var clean = t.toLowerCase();
    white.forEach(function (w) { clean = clean.split(w).join(' '); });
    if (lang === 'zh' && /[a-z]{2,}/.test(clean)) { flag(t, 'Latin in zh'); continue; }
    words(t).forEach(function (w) {
      if (foreign[w] && clean.indexOf(w) >= 0) flag(t, 'foreign word: ' + w);
    });
  }
  if (doc.title) {
    var tt = doc.title.toLowerCase();
    white.forEach(function (w) { tt = tt.split(w).join(' '); });
    if (lang !== 'zh' && /[\u4e00-\u9fff]/.test(doc.title)) flag(doc.title, 'CJK in title');
    if (lang === 'zh' && /[a-z]{2,}/.test(tt)) flag(doc.title, 'Latin in title');
  }
  return bad;
};
'''
    OUT.write_text(js)
    coverage['counts'] = {
        'keys': len(data['t']),
        'products': len(data['products']),
        'js_bytes': len(js.encode()),
        'missing': len(coverage['missing']),
    }
    if not COVERAGE.parent.exists():
        COVERAGE.parent.mkdir()
    COVERAGE.write_text(json.dumps(coverage, ensure_ascii=False, indent=2))
    print('i18n.js: %d keys, %d products, %d bytes' % (
        len(data['t']), len(data['products']), len(js.encode())))
    for name, st in coverage['pages'].items():
        print('  %-24s %s' % (name, st))
    if coverage['missing']:
        print('\nMISSING TRANSLATIONS (%d):' % len(coverage['missing']))
        for x in coverage['missing'][:40]:
            print('  ', x['page'], repr(x['text']))
        raise SystemExit(2)
    print('\nAll visible strings have en/fr/zh translations.')


if __name__ == '__main__':
    main()
